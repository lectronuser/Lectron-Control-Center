#!/usr/bin/env python3
"""Generates lib/core/frames.g.dart from ArduPilot's libraries/AP_Motors/AP_MotorsMatrix.cpp.

Every frame defined with a MotorDef table (angle, yaw factor, test order) is included; frames set up in code
(Tri, Y6, scripting) are not, so no diagram is shown for them rather than a wrong one.

    python3 tool/gen_frames.py ~/ardupilot && dart format lib/core/frames.g.dart
"""
import math
import os
import re
import sys

ROOT = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else '~/ardupilot')
SRC = os.path.join(ROOT, 'libraries', 'AP_Motors', 'AP_MotorsMatrix.cpp')
ENUMS = os.path.join(ROOT, 'libraries', 'AP_Motors', 'AP_Motors_Class.h')
OUT = os.path.join(os.path.dirname(__file__), '..', 'lib', 'core', 'frames.g.dart')

CLASS_FUNCS = {
    'quad': ('QUAD', 'Quad'),
    'hexa': ('HEXA', 'Hexa'),
    'octa': ('OCTA', 'Octa'),
    'octaquad': ('OCTAQUAD', 'OctaQuad'),
    'dodecahexa': ('DODECAHEXA', 'DodecaHexa'),
    'deca': ('DECA', 'Deca'),
}
TYPE_NAMES = {
    'PLUS': '+', 'X': 'X', 'V': 'V', 'H': 'H', 'VTAIL': 'V-tail', 'ATAIL': 'A-tail', 'PLUSREV': '+ reversed',
    'Y6B': 'Y6B', 'Y6F': 'Y6F', 'BF_X': 'X (Betaflight)', 'DJI_X': 'X (DJI)', 'CW_X': 'X (clockwise)', 'I': 'I',
    'NYT_PLUS': '+ (no yaw torque)', 'NYT_X': 'X (no yaw torque)', 'BF_X_REV': 'X (Betaflight, reversed)', 'Y4': 'Y4',
    'X_COR': 'X co-rotating', 'CW_X_COR': 'X co-rotating (clockwise)',
}


def enum_values(text, prefix):
    return {m.group(1): int(m.group(2)) for m in re.finditer(r'\b' + prefix + r'(\w+)\s*=\s*(\d+)', text)}


def main():
    src = open(SRC).read()
    enums = open(ENUMS).read()
    classes = enum_values(enums, 'MOTOR_FRAME_')
    types = enum_values(enums, 'MOTOR_FRAME_TYPE_')
    entry = re.compile(r'\{\s*(-?[\d.]+)f?\s*,\s*(AP_MOTORS_MATRIX_YAW_FACTOR_CW|AP_MOTORS_MATRIX_YAW_FACTOR_CCW|-?[\d.]+f?)\s*,\s*(\d+)\s*\}')
    out = {}
    for func, (cls, cls_name) in CLASS_FUNCS.items():
        m = re.search(r'bool AP_MotorsMatrix::setup_' + func + r'_matrix\(.*?\n\}\n', src, re.S)
        if not m:
            continue
        body = m.group(0)
        for case in re.finditer(r'case MOTOR_FRAME_TYPE_(\w+):\s*\{(.*?)\n    \}', body, re.S):
            name, block = case.group(1), case.group(2)
            table = re.search(r'MotorDef motors\[\]\s*\{(.*?)\};', block, re.S)
            if not table:
                continue
            motors = []
            for number, e in enumerate(entry.finditer(table.group(1)), start=1):
                angle = float(e.group(1))
                yaw = e.group(2)
                cw = yaw.endswith('_CW') or (not yaw.startswith('AP_') and float(yaw.rstrip('f')) < 0)
                motors.append((int(e.group(3)), angle, number, cw))
            if not motors:
                continue
            motors.sort()
            out[(classes[cls], types[name])] = (f'{cls_name} {TYPE_NAMES.get(name, name)}', motors)

    lines = [
        '// GENERATED by tool/gen_frames.py from ArduPilot AP_MotorsMatrix.cpp. Do not edit by hand.',
        '',
        "part of 'board_controller.dart';",
        '',
        '/// ArduPilot frame layouts by (FRAME_CLASS, FRAME_TYPE), motors in test order (A, B, C, ...).',
        'const Map<(int, int), FrameLayout> apFrameLayouts = {',
    ]
    for (cls, typ), (name, motors) in sorted(out.items()):
        lines.append(f"  ({cls}, {typ}): FrameLayout('{name}', [")
        for _, angle, number, cw in motors:
            x = math.cos(math.radians(angle))
            y = math.sin(math.radians(angle))
            lines.append(f'    ({x:.4f}, {y:.4f}, {number}, {"true" if cw else "false"}),')
        lines.append('  ]),')
    lines.append('};')
    with open(OUT, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'{len(out)} frames')


if __name__ == '__main__':
    main()
