#!/usr/bin/env python3
"""Generates lib/mavlink/mavlink_defs.g.dart from pymavlink (ardupilotmega dialect).

Only the messages and enums the app uses are emitted. Run from the project root:
    python3 tool/gen_mavlink.py
"""
import os

os.environ.setdefault("MAVLINK20", "1")
from pymavlink import mavutil  # noqa: E402

mavlink = mavutil.mavlink

MESSAGES = [
    "HEARTBEAT", "SYS_STATUS", "SYSTEM_TIME", "PARAM_REQUEST_READ", "PARAM_REQUEST_LIST", "PARAM_VALUE",
    "PARAM_SET", "GPS_RAW_INT", "SCALED_IMU", "RAW_IMU", "SCALED_PRESSURE", "ATTITUDE", "SERVO_OUTPUT_RAW",
    "RC_CHANNELS", "REQUEST_DATA_STREAM", "VFR_HUD", "COMMAND_LONG", "COMMAND_ACK", "OPTICAL_FLOW",
    "HIGHRES_IMU", "SCALED_IMU2", "GPS2_RAW", "POWER_STATUS", "SCALED_IMU3", "DISTANCE_SENSOR",
    "SCALED_PRESSURE2", "SCALED_PRESSURE3", "BATTERY_STATUS", "AUTOPILOT_VERSION", "MEMINFO", "HWSTATUS",
    "RANGEFINDER", "EKF_STATUS_REPORT", "STATUSTEXT", "MCU_STATUS",
]
ENUMS = {
    "MAV_TYPE": "MAV_TYPE_", "MAV_AUTOPILOT": "MAV_AUTOPILOT_", "MAV_STATE": "MAV_STATE_",
    "MAV_SEVERITY": "MAV_SEVERITY_", "MAV_CMD": "MAV_CMD_", "MAV_RESULT": "MAV_RESULT_",
    "MAV_PARAM_TYPE": "MAV_PARAM_TYPE_", "MAV_SYS_STATUS_SENSOR": "MAV_SYS_STATUS_SENSOR_",
}
SIZES = {"char": 1, "int8_t": 1, "uint8_t": 1, "int16_t": 2, "uint16_t": 2, "int32_t": 4, "uint32_t": 4,
         "float": 4, "int64_t": 8, "uint64_t": 8, "double": 8}
TYPES = {"char": "c", "int8_t": "i8", "uint8_t": "u8", "int16_t": "i16", "uint16_t": "u16", "int32_t": "i32",
         "uint32_t": "u32", "float": "f32", "int64_t": "i64", "uint64_t": "u64", "double": "f64"}


def camel(name):
    parts = name.lower().split("_")
    return parts[0] + "".join(p.title() for p in parts[1:])


def pretty(name, prefix):
    # a few MAV_SYS_STATUS entries (LOGGING, AHRS, ...) do not carry the full SENSOR_ prefix
    name = name.replace(prefix, "").replace("MAV_SYS_STATUS_", "")
    return name.replace("_", " ").title()


out = ["// GENERATED by tool/gen_mavlink.py from pymavlink (ardupilotmega). Do not edit by hand.",
       "// ignore_for_file: constant_identifier_names", "", "part of 'mavlink.dart';", ""]

out.append("abstract final class MavId {")
for name in MESSAGES:
    cls = getattr(mavlink, f"MAVLink_{name.lower()}_message")
    out.append(f"  static const int {camel(name)} = {cls.id};")
out.append("}")
out.append("")

out.append("const Map<int, MavDef> mavDefs = {")
for name in MESSAGES:
    cls = getattr(mavlink, f"MAVLink_{name.lower()}_message")
    offset = 0
    fields = []
    for i, field in enumerate(cls.ordered_fieldnames):
        ftype = cls.fieldtypes[cls.fieldnames.index(field)]
        count = cls.array_lengths[i]
        fields.append(f"MavField('{field}', MavType.{TYPES[ftype]}, {offset}, {count})")
        offset += SIZES[ftype] * max(count, 1)
    assert offset == cls.unpacker.size, name
    out.append(f"  {cls.id}: MavDef({cls.id}, '{name}', {cls.crc_extra}, {offset}, [")
    out.extend(f"    {f}," for f in fields)
    out.append("  ]),")
out.append("};")
out.append("")

for enum, prefix in ENUMS.items():
    out.append(f"const Map<int, String> {camel(enum)}Names = {{")
    for value, entry in sorted(mavlink.enums[enum].items()):
        if entry.name.endswith("_ENUM_END"):
            continue
        out.append(f"  {value}: '{pretty(entry.name, prefix)}',")
    out.append("};")
    out.append("")

# ArduPilot flight modes; vehicle types that share a table share one constant
tables = {}
by_type = {}
for mav_type in sorted(mavlink.enums["MAV_TYPE"]):
    modes = mavutil.mode_mapping_bynumber(mav_type)
    if not modes:
        continue
    key = tuple(sorted(modes.items()))
    tables.setdefault(key, f"_apModes{len(tables)}")
    by_type[mav_type] = tables[key]
for key, const in tables.items():
    out.append(f"const Map<int, String> {const} = {{")
    out.extend(f"  {number}: '{name}'," for number, name in key)
    out.append("};")
    out.append("")
out.append("/// MAV_TYPE -> custom_mode -> ArduPilot flight mode name.")
out.append("const Map<int, Map<int, String>> ardupilotModes = {")
out.extend(f"  {mav_type}: {const}," for mav_type, const in by_type.items())
out.append("};")
out.append("")

path = os.path.join(os.path.dirname(__file__), "..", "lib", "mavlink", "mavlink_defs.g.dart")
with open(path, "w") as f:
    f.write("\n".join(out))
print(f"{len(MESSAGES)} messages -> {os.path.normpath(path)}")
