#!/usr/bin/env python3
"""Generates lib/mavlink/mavlink_defs.g.dart from pymavlink's ardupilotmega dialect.

Every message of the dialect is included, so the MAVLink Inspector, missions, MAVLink FTP, log download and
the calibrations can decode whatever the vehicle sends.

    python3 tool/gen_mavlink.py && dart format lib/mavlink/mavlink_defs.g.dart
"""
import os
import re

from pymavlink import mavutil
from pymavlink.dialects.v20 import ardupilotmega as mav

OUT = os.path.join(os.path.dirname(__file__), '..', 'lib', 'mavlink', 'mavlink_defs.g.dart')

TYPES = {
    'char': 'c', 'int8_t': 'i8', 'uint8_t': 'u8', 'uint8_t_mavlink_version': 'u8', 'int16_t': 'i16',
    'uint16_t': 'u16', 'int32_t': 'i32', 'uint32_t': 'u32', 'float': 'f32', 'int64_t': 'i64', 'uint64_t': 'u64',
    'double': 'f64',
}
SIZES = {'c': 1, 'i8': 1, 'u8': 1, 'i16': 2, 'u16': 2, 'i32': 4, 'u32': 4, 'f32': 4, 'i64': 8, 'u64': 8, 'f64': 8}

# (dart name, MAVLink enum, prefix stripped from the entry names)
ENUMS = [
    ('mavTypeNames', 'MAV_TYPE', 'MAV_TYPE_'),
    ('mavAutopilotNames', 'MAV_AUTOPILOT', 'MAV_AUTOPILOT_'),
    ('mavStateNames', 'MAV_STATE', 'MAV_STATE_'),
    ('mavSeverityNames', 'MAV_SEVERITY', 'MAV_SEVERITY_'),
    ('mavCmdNames', 'MAV_CMD', 'MAV_CMD_'),
    ('mavResultNames', 'MAV_RESULT', 'MAV_RESULT_'),
    ('mavParamTypeNames', 'MAV_PARAM_TYPE', 'MAV_PARAM_TYPE_'),
    ('mavSysStatusSensorNames', 'MAV_SYS_STATUS_SENSOR', 'MAV_SYS_STATUS_SENSOR_'),
    ('mavFrameNames', 'MAV_FRAME', 'MAV_FRAME_'),
    ('mavMissionResultNames', 'MAV_MISSION_RESULT', 'MAV_MISSION_'),
    ('gpsFixTypeNames', 'GPS_FIX_TYPE', 'GPS_FIX_TYPE_'),
    ('magCalStatusNames', 'MAG_CAL_STATUS', 'MAG_CAL_'),
    ('accelcalVehiclePosNames', 'ACCELCAL_VEHICLE_POS', 'ACCELCAL_VEHICLE_POS_'),
]


def camel(name):
    head, *rest = name.lower().split('_')
    return head + ''.join(w[:1].upper() + w[1:] for w in rest)


def title(name, prefix):
    # a few newer entries drop part of the prefix, e.g. MAV_SYS_STATUS_GEOFENCE
    for p in (prefix, prefix.rsplit('_', 2)[0] + '_'):
        if name.startswith(p):
            return name[len(p):].replace('_', ' ').title()
    return name


def dart_str(text):
    return "'" + text.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"


def message_def(msg_id, cls):
    fields = []
    offset = 0
    # fieldtypes follow the XML order, array_lengths the wire order
    for wire, name in enumerate(cls.ordered_fieldnames):
        t = TYPES[cls.fieldtypes[cls.fieldnames.index(name)]]
        count = cls.array_lengths[wire]
        fields.append((name, t, offset, count))
        offset += SIZES[t] * max(count, 1)
    lines = [f"  {msg_id}: MavDef({msg_id}, '{cls.msgname}', {cls.crc_extra}, {offset}, ["]
    lines += [f"    MavField('{n}', MavType.{t}, {o}, {c})," for n, t, o, c in fields]
    lines.append('  ]),')
    return lines


def main():
    msgs = sorted(mav.mavlink_map.items())
    out = [
        '// GENERATED by tool/gen_mavlink.py from pymavlink (ardupilotmega). Do not edit by hand.',
        '// ignore_for_file: constant_identifier_names',
        '',
        "part of 'mavlink.dart';",
        '',
        'abstract final class MavId {',
    ]
    out += [f'  static const int {camel(cls.msgname)} = {msg_id};' for msg_id, cls in msgs]
    out += ['}', '', 'const Map<int, MavDef> mavDefs = {']
    for msg_id, cls in msgs:
        out += message_def(msg_id, cls)
    out += ['};', '']

    for dart, enum, prefix in ENUMS:
        out.append(f'const Map<int, String> {dart} = {{')
        for value, entry in sorted(mav.enums[enum].items()):
            if entry.name.endswith('_ENUM_END'):
                continue
            out.append(f'  {value}: {dart_str(title(entry.name, prefix))},')
        out += ['};', '']

    # MAV_CMD descriptions and the meaning of each param, for the mission editor
    out.append('/// MAV_CMD -> (description, labels of param1..7; empty when unused).')
    out.append('const Map<int, (String, List<String>)> mavCmdInfo = {')
    for value, entry in sorted(mav.enums['MAV_CMD'].items()):
        if entry.name.endswith('_ENUM_END'):
            continue
        labels = []
        for i in range(1, 8):
            p = entry.param.get(i, '') if isinstance(entry.param, dict) else ''
            labels.append(re.sub(r'\s+', ' ', p or '').strip())
        desc = re.sub(r'\s+', ' ', entry.description or '').strip()
        out.append(f'  {value}: ({dart_str(desc)}, [{", ".join(dart_str(l) for l in labels)}]),')
    out += ['};', '']

    # ArduPilot flight modes per MAV_TYPE, shared maps written once
    maps = []
    by_type = {}
    for mav_type, modes in sorted(mavutil.AP_MAV_TYPE_MODE_MAP.items()):
        if modes not in maps:
            maps.append(modes)
        by_type[mav_type] = maps.index(modes)
    for i, modes in enumerate(maps):
        out.append(f'const Map<int, String> _apModes{i} = {{')
        out += [f"  {k}: '{v}'," for k, v in sorted(modes.items())]
        out += ['};', '']
    out.append('/// MAV_TYPE -> custom_mode -> ArduPilot flight mode name.')
    out.append('const Map<int, Map<int, String>> ardupilotModes = {')
    out += [f'  {t}: _apModes{i},' for t, i in sorted(by_type.items())]
    out.append('};')

    with open(OUT, 'w') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
